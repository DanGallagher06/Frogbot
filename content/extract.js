// Frogbot: finds the page's article content as a list of text blocks.
// Defines window.FrogbotExtract with findMainContainer() and getBlocks().
(() => {
  if (window.FrogbotExtract) return;

  const MAX_BLOCKS = 1500;
  const MIN_CONTAINER_CHARS = 500;
  const MIN_PLAIN_CHARS = 25; // shorter blocks are kept only if they contain a digit
  const MAX_LINK_SHARE = 0.6;
  const MIN_DIV_CHARS = 40; // a text-only <div>/<span> needs this much text to count

  // Checked in order. Wikipedia's article body comes first: it's more specific than
  // its <main>, which also holds the page title bar and tools.
  const CONTAINER_SELECTORS = ["#mw-content-text", "article", "main", "[role='main']", "#content"];

  const BLOCK_TAGS = new Set(["P", "LI", "TD", "TH", "H2", "H3", "H4", "BLOCKQUOTE", "FIGCAPTION", "DD"]);
  // Anything block-level. A <div> or <span> containing none of these is "text-only" and
  // can be a paragraph itself (some sites, e.g. Apple's newsroom, write paragraphs as divs).
  const BLOCK_LEVEL_TAGS = new Set(
    ("P DIV LI UL OL DL DT DD TABLE TR TD TH SECTION ARTICLE ASIDE NAV HEADER FOOTER MAIN " +
      "FORM FIGURE FIGCAPTION BLOCKQUOTE PRE H1 H2 H3 H4 H5 H6").split(" ")
  );
  const BLOCKISH_DISPLAY = new Set(["block", "flex", "grid", "flow-root", "list-item"]);
  const EXCLUDED_TAGS = new Set(["NAV", "HEADER", "FOOTER", "ASIDE", "FORM", "BUTTON"]);
  // Notice and maintenance boxes (Wikipedia's hatnotes, "neutrality disputed" etc.).
  const NOTICE_CLASS = /(?:^|\s)(?:ambox|ombox|tmbox|metadata|hatnote)(?:\s|$)/;
  // End-of-article sections. Everything after one of these h2s is skipped, up to the next h2.
  const END_SECTION = /^(?:see also|references|notes|citations|sources|further reading|external links|bibliography)$/i;

  // Matched against class names and ids at a word start ("site-nav", "mainMenu", "navbox"),
  // so "lead-in" doesn't match "ad-" and "canvas" doesn't match "nav".
  const JUNK_NAME =
    /(?:^|[\s_-])(?:nav|menu|footer|sidebar|breadcrumb|comment|related|share(?!holder)|social|promo|advert|ad-|sponsor|cookie|newsletter|subscribe|popup|modal|navbox|reflist|references|key-?points|key-?takeaways|takeaways|ai-summary|summary-box|article-summary|tldr)/;

  // Caption and credit class names. Unlike JUNK_NAME these never exclude a whole wrapper:
  // a news site's lead wrapper ("has-caption") can hold the opening paragraphs too.
  const CAPTION_NAME = /(?:^|[\s_-])(?:caption|credit)/;

  // Audio and video player widgets ("tts-player", "audioPlayer", "listen-button"). Like
  // captions, these only count on small elements, never on a wrapper holding the article.
  const PLAYER_NAME = /(?:^|[\s_-])(?:audio|player|podcast|listen|tts|text-to-speech)/;
  const PLAYER_CONTROLS =
    'audio, video, button[aria-label*="play" i], button[aria-label*="pause" i], [role="button"][aria-label*="play" i]';
  const MAX_WIDGET_CHARS = 400;
  // Short boilerplate lines that sit under players and AI features.
  const DISCLAIMER_TEXT = /generated by AI|AI[- ]generated|Listen to (?:this )?article|Learn more/i;
  const MAX_DISCLAIMER_CHARS = 150;

  // Summary widgets labelled for screen readers rather than by class.
  const SUMMARY_LABEL = /key (?:points|takeaways)|takeaways|ai[- ](?:generated|summary)|tl;?dr/i;

  // Photo credits and caption giveaways in a block's own text. A bare "Getty Images" only
  // counts when it ends a short credit line, so sentences about the company survive.
  const CAPTION_TEXT =
    /\(Photo by|\bPhoto:|\bImage:|via Getty Images|\/\s?Getty Images|\bReuters\/|\bAP Photo|Shutterstock/i;
  const CREDIT_ENDING = /Getty Images\)?\.?$/i;
  const MAX_CAPTION_CHARS = 200; // a caption after an image is at most this long...
  const CAPTION_FONT_RATIO = 0.9; // ...and set smaller than the article's paragraphs
  const MEDIA_TAGS = "img, picture, video, svg";
  // Image wrappers by class: "image-embed", "article__photo", "mediaWrapper".
  const IMAGE_WRAPPER_NAME = /(?:^|[\s_-])(?:image|img|photo|picture|media|figure)(?:[\s_-]|$)/;
  const MAX_IMAGE_WRAPPER_CHARS = 400;

  // Wikipedia-style citation and edit markers: [1], [a], [note 3], [citation needed], [edit].
  const MARKERS =
    /\[\s*(?:\d+|[a-z]{1,2}|(?:note|nb|n)\s*\d+|citation needed|clarification needed|edit)\s*\]/gi;

  const collapse = (text) => text.replace(/\s+/g, " ").trim();

  function junkName(el) {
    // className is an object on SVG elements; getAttribute works everywhere.
    const names = `${el.getAttribute("class") || ""} ${el.id || ""}`;
    if (names.length < 2) return false;
    // Split camelCase so "relatedStories" reads as "related-stories".
    return JUNK_NAME.test(names.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase());
  }

  // display:none (on it or any ancestor), visibility:hidden, or zero size.
  function isRendered(el) {
    if (!el.checkVisibility({ visibilityProperty: true })) return false;
    const rect = el.getBoundingClientRect();
    return rect.width > 0 && rect.height > 0;
  }

  function hasEnoughText(el) {
    return (
      el.textContent.length >= MIN_CONTAINER_CHARS &&
      !el.closest("[aria-hidden='true']") &&
      isRendered(el)
    );
  }

  // Visible text. Plain-text elements (most table cells) can use the much cheaper
  // textContent; anything with child elements needs innerText to skip hidden parts.
  const visibleText = (el) =>
    collapse((el.childElementCount ? el.innerText : el.textContent).replace(MARKERS, ""));

  // Score div/section elements by the non-link paragraph text they hold.
  // Each paragraph credits its nearest container fully and the next one up by half.
  function bestScoringContainer() {
    const scores = new Map();
    const credit = (el, points) => {
      if (el) scores.set(el, (scores.get(el) || 0) + points);
    };
    for (const p of document.body.querySelectorAll("p")) {
      let linkChars = 0;
      for (const a of p.querySelectorAll("a")) linkChars += collapse(a.textContent).length;
      const points = collapse(p.textContent).length - linkChars;
      if (points <= 0) continue;
      const parent = p.parentElement && p.parentElement.closest("div, section");
      const grandparent = parent && parent.parentElement && parent.parentElement.closest("div, section");
      credit(parent, points);
      credit(grandparent, points / 2);
    }
    let best = null;
    let bestScore = 0;
    for (const [el, score] of scores) {
      if (score > bestScore) {
        best = el;
        bestScore = score;
      }
    }
    return best;
  }

  function findMainContainer() {
    for (const selector of CONTAINER_SELECTORS) {
      const el = document.querySelector(selector);
      if (el && hasEnoughText(el)) return el;
    }
    return bestScoringContainer() || document.body;
  }

  function typeOf(el) {
    switch (el.tagName) {
      case "LI":
      case "DD":
        return "list";
      case "TD":
      case "TH":
        return "table";
      case "H2":
      case "H3":
      case "H4":
        return "heading";
      case "BLOCKQUOTE":
        return "quote";
      default:
        // A <p> or <figcaption> takes the type of the structure it sits in.
        if (el.closest("blockquote")) return "quote";
        if (el.closest("td, th")) return "table";
        if (el.closest("li, dd")) return "list";
        return "paragraph";
    }
  }

  // One regex over the class string: much cheaper than several classList checks per element.
  const isNotice = (el) => el.getAttribute("role") === "note" || NOTICE_CLASS.test(el.getAttribute("class") || "");

  const isSummaryWidget = (el) => SUMMARY_LABEL.test(el.getAttribute("aria-label") || "");

  const classNames = (el) =>
    (el.getAttribute("class") || "").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

  // A <figure> or image wrapper: holds an image and isn't a table. It may also hold article
  // paragraphs (news sites often wrap the lead photo and opening paragraphs together), so
  // being inside one never excludes a block by itself; see isCaptionBlock().
  function isImageWrapper(el) {
    return (
      (el.tagName === "FIGURE" || IMAGE_WRAPPER_NAME.test(classNames(el))) &&
      el.querySelector(MEDIA_TAGS) !== null &&
      el.querySelector("table") === null
    );
  }

  // Nothing but an image: <img>, <picture>, or a wrapper with media and next to no text.
  // (A <figure> with its own caption doesn't count; its caption is handled separately.)
  const isImageOnly = (el) =>
    !!el &&
    (/^(?:IMG|PICTURE|VIDEO)$/.test(el.tagName) ||
      (el.textContent.trim().length < 20 && el.querySelector(MEDIA_TAGS) !== null));

  const fontSize = (el) => parseFloat(getComputedStyle(el).fontSize) || 0;

  // Typical article text size: the median font size of the container's first paragraphs.
  function articleFontSize(container) {
    const sizes = [...container.querySelectorAll("p")].slice(0, 30).map(fontSize).sort((a, b) => a - b);
    return sizes.length ? sizes[Math.floor(sizes.length / 2)] : 0;
  }

  // A short, small-print block straight after an image is a caption even without
  // <figcaption>. Real paragraphs often follow images too, but in the article's own size.
  const followsImage = (el, text, bodySize) =>
    text.length <= MAX_CAPTION_CHARS && isImageOnly(el.previousElementSibling) && isSmallPrint(el, bodySize);

  const isCaptionText = (text) =>
    CAPTION_TEXT.test(text) || (text.length <= MAX_CAPTION_CHARS && CREDIT_ENDING.test(text));

  const isSmallPrint = (el, bodySize) => bodySize > 0 && fontSize(el) <= bodySize * CAPTION_FONT_RATIO;

  // Inside an audio/video player widget: a small element named like a player, or one that
  // holds media or play/pause controls.
  // `sizeOf` returns an element's text length, measured once per element: rebuilding a whole
  // table's text for each of its cells would be slow on big financial tables.
  function inPlayerWidget(el, container, playerCache, sizeOf) {
    for (let node = el; node && node !== container; node = node.parentElement) {
      if (sizeOf(node) > MAX_WIDGET_CHARS) break; // ancestors only get bigger
      if (!playerCache.has(node)) {
        playerCache.set(
          node,
          PLAYER_NAME.test(classNames(node) + " " + (node.id || "").toLowerCase()) ||
            (node.firstElementChild !== null && node.querySelector(PLAYER_CONTROLS) !== null)
        );
      }
      if (playerCache.get(node)) return true;
    }
    return false;
  }

  const isDisclaimer = (text) => text.length < MAX_DISCLAIMER_CHARS && DISCLAIMER_TEXT.test(text);

  // Is this block a caption, judged on the block itself rather than its wrapper?
  // - a <figcaption> of a picture (a table's figcaption is content)
  // - inside a caption/credit-named element that is caption-sized, not a whole section
  // - short small print inside an image wrapper (or the wrapper itself, e.g. an infobox image cell)
  function isCaptionBlock(el, text, bodySize, container, wrapperCache) {
    const wrapperOf = (node) => {
      if (!wrapperCache.has(node)) wrapperCache.set(node, isImageWrapper(node));
      return wrapperCache.get(node);
    };
    for (let node = el; node && node !== container; node = node.parentElement) {
      if (node.tagName === "FIGCAPTION" && node.parentElement && wrapperOf(node.parentElement)) return true;
      if (CAPTION_NAME.test(classNames(node) + " " + (node.id || "").toLowerCase()) &&
          node.textContent.length <= MAX_IMAGE_WRAPPER_CHARS) {
        return true;
      }
      if (text.length <= MAX_CAPTION_CHARS && wrapperOf(node) && isSmallPrint(el, bodySize)) return true;
    }
    return false;
  }

  // Collapsed content: a closed <details> (outside its <summary>), a region whose toggle
  // says aria-expanded="false", or a box squashed to ~zero height with its overflow hidden.
  function isCollapsed(node, closedRegions, el) {
    if (node.tagName === "DETAILS" && !node.open) {
      const summary = el.closest("summary");
      return !(summary && node.contains(summary));
    }
    if (node.getAttribute("aria-expanded") === "false" && !/^(?:BUTTON|A|SUMMARY)$/.test(node.tagName)) {
      return true;
    }
    if (node.id && closedRegions.has(node.id)) return true;
    // Only ancestors: a squashed block itself has no size and fails isRendered() anyway, and
    // reading layout heights for every block is slow on big tables. Ancestor verdicts are
    // cached, so each one is measured once. Only boxes that look squashed pay for
    // getComputedStyle.
    if (node !== el && node.clientHeight <= 4 && node.scrollHeight > 20) {
      const style = getComputedStyle(node);
      return /hidden|clip/.test(style.overflowY) || style.maxHeight === "0px";
    }
    return false;
  }

  // True if any ancestor (below the container) is in `set`.
  function hasAncestorIn(el, set, container) {
    for (let node = el.parentElement; node && node !== container; node = node.parentElement) {
      if (set.has(node)) return true;
    }
    return false;
  }

  function getBlocks(container = findMainContainer()) {
    // One backwards walk over every element, checking tag names in Sets: several times
    // faster than querySelectorAll with long selector lists on big pages. Walking
    // backwards means an element's descendants have all been seen before it.
    const all = container.getElementsByTagName("*");
    const hasBlockInside = new Set();
    const candidates = [];
    const standard = new Set();
    for (let i = all.length - 1; i >= 0; i--) {
      const el = all[i];
      const tag = el.tagName;
      if (BLOCK_TAGS.has(tag)) {
        candidates.push(el);
        standard.add(el);
      } else if (
        // A div or span qualifies only if it holds no block-level elements and enough text.
        (tag === "DIV" || tag === "SPAN") &&
        !hasBlockInside.has(el) &&
        el.textContent.length >= MIN_DIV_CHARS
      ) {
        candidates.push(el);
      }
      if (BLOCK_LEVEL_TAGS.has(tag) || hasBlockInside.has(el)) hasBlockInside.add(el.parentElement);
    }
    candidates.reverse(); // back to document order

    // Innermost blocks only: an <li> holding a <p> gives way to the <p>.
    const hasInnerBlock = new Set();
    for (const el of standard) {
      for (let node = el.parentElement; node && node !== container; node = node.parentElement) {
        if (standard.has(node)) {
          hasInnerBlock.add(node);
          break;
        }
      }
    }
    // A text-only div/span inside another candidate is part of that block, not a new one.
    const textOnly = new Set();
    function acceptTextOnly(el) {
      if (hasAncestorIn(el, standard, container) || hasAncestorIn(el, textOnly, container)) return false;
      if (el.tagName === "SPAN" && !BLOCKISH_DISPLAY.has(getComputedStyle(el).display)) return false;
      textOnly.add(el);
      return true;
    }

    // Regions controlled by a collapsed toggle: <button aria-expanded="false" aria-controls="x">.
    const closedRegions = new Set();
    for (const toggle of document.querySelectorAll('[aria-expanded="false"][aria-controls]')) {
      for (const id of toggle.getAttribute("aria-controls").split(/\s+/)) if (id) closedRegions.add(id);
    }

    // Ancestor verdicts are cached: neighbouring blocks share most of their ancestors.
    // Chains through a <details> aren't cached: whether it hides a block depends on
    // whether the block is in its <summary>.
    const excludedCache = new Map();
    function inExcludedArea(el) {
      const chain = [];
      let node = el;
      let verdict = false;
      let cacheable = true;
      while (node && node !== container) {
        if (excludedCache.has(node)) {
          verdict = excludedCache.get(node);
          break;
        }
        if (node.tagName === "DETAILS") cacheable = false;
        chain.push(node);
        if (
          EXCLUDED_TAGS.has(node.tagName) ||
          node.getAttribute("aria-hidden") === "true" ||
          junkName(node) ||
          isNotice(node) ||
          isSummaryWidget(node) ||
          isCollapsed(node, closedRegions, el) ||
          (typeof node.className === "string" && node.className.includes("frogbot-"))
        ) {
          verdict = true;
          break;
        }
        node = node.parentElement;
      }
      if (cacheable) for (const n of chain) excludedCache.set(n, verdict);
      return verdict;
    }

    const blocks = [];
    let inEndSection = false;
    let bodySize; // measured on first need
    const wrapperCache = new Map();
    const playerCache = new Map();
    const sizes = new Map();
    const sizeOf = (node) => {
      if (!sizes.has(node)) sizes.set(node, node.textContent.length);
      return sizes.get(node);
    };
    for (const el of candidates) {
      if (blocks.length >= MAX_BLOCKS) break;
      // End sections: h2s are candidates too, and candidates are in document order,
      // so each h2 switches skipping on or off for everything after it.
      if (el.tagName === "H2") {
        inEndSection = END_SECTION.test(collapse(el.textContent.replace(MARKERS, "")));
      }
      if (inEndSection) continue;

      const isStandard = standard.has(el);
      if (isStandard ? hasInnerBlock.has(el) : !acceptTextOnly(el)) continue;
      if (inExcludedArea(el)) continue;

      // Cheap text checks first: they drop empty and label cells before any layout work.
      const text = visibleText(el);
      if (!text) continue;
      if (isStandard ? text.length < MIN_PLAIN_CHARS && !/\d/.test(text) : text.length < MIN_DIV_CHARS) {
        continue;
      }
      if (!isRendered(el)) continue;
      // Captions and photo credits without a <figcaption>.
      if (isCaptionText(text)) continue;
      if (bodySize === undefined) bodySize = articleFontSize(container);
      if (followsImage(el, text, bodySize)) continue;
      if (isCaptionBlock(el, text, bodySize, container, wrapperCache)) continue;
      // Audio players and the "generated by AI" style lines beneath them.
      if (isDisclaimer(text) || inPlayerWidget(el, container, playerCache, sizeOf)) continue;

      const links = el.getElementsByTagName("a");
      if (links.length) {
        let linkChars = 0;
        // textContent is close enough for link text and far cheaper than innerText.
        for (const a of links) linkChars += collapse(a.textContent.replace(MARKERS, "")).length;
        if (linkChars / text.length > MAX_LINK_SHARE) continue;
      }

      blocks.push({ element: el, text, type: typeOf(el), index: blocks.length });
    }
    return blocks;
  }

  // ---------------------------------------------------------------------------
  // Scoring units (step 8): prose sentences and table rows, ready for FrogbotScore.rankUnits()
  // ---------------------------------------------------------------------------

  const PROSE_TYPES = new Set(["paragraph", "list", "quote"]);
  const NOT_FIGURES = new Set(["period", "year", "date"]);
  // Citation markers only need stripping when there's a "[" (most cells have none).
  const cellText = (cell) => {
    const raw = cell.textContent;
    return collapse(raw.includes("[") ? raw.replace(MARKERS, "") : raw);
  };

  // One entry per column, with colspans expanded.
  function expandRow(tr) {
    const cols = [];
    for (const cell of tr.cells) for (let i = 0; i < Math.max(1, cell.colSpan || 1); i++) cols.push(cell);
    return cols;
  }

  // A table's column-header row: the last <thead> row, else the first row of <th> cells,
  // else an early row whose cells are mostly periods ("Q3 2026", "FY25").
  function headerRowOf(table, score) {
    if (table.tHead && table.tHead.rows.length) return table.tHead.rows[table.tHead.rows.length - 1];
    const early = [...table.rows].slice(0, 4);
    const allTh = early.find((r) => r.cells.length >= 2 && [...r.cells].every((c) => c.tagName === "TH"));
    if (allTh) return allTh;
    const periodRow = early.find((r) => {
      const texts = [...r.cells].map(cellText).filter(Boolean);
      if (texts.length < 2) return false;
      const periods = texts.filter((t) =>
        score.detectNumbers(t).some((n) => !n.junk && NOT_FIGURES.has(n.type))
      ).length;
      return periods >= Math.ceil(texts.length / 2);
    });
    return periodRow || null;
  }

  // Units for scoring, in page order:
  // - each sentence of a paragraph, list item or quote
  // - each table row with at least one extracted figure cell, its cells joined with " | ",
  //   plus the column headers above its figures; the hop target is its first figure cell
  // Headings aren't units, but a heading with a number marks the sentences under it.
  // `score` is FrogbotScore (passed in because extract.js loads first).
  function buildUnits(blocks, score) {
    const units = [];
    const rowUnits = new Map(); // tr -> unit (or null for header/figureless rows)
    const headerRows = new Map(); // table -> { row, texts }
    // Cells holding extracted blocks, by row, so a row's target is something the frog read.
    const blockCells = new Map(); // tr -> Set of cells
    for (const b of blocks) {
      const cell = b.type === "table" && b.element.closest("td, th");
      if (!cell) continue;
      if (!blockCells.has(cell.parentElement)) blockCells.set(cell.parentElement, new Set());
      blockCells.get(cell.parentElement).add(cell);
    }
    let headingHasNumber = false;

    for (const block of blocks) {
      if (block.type === "heading") {
        headingHasNumber = score.detectNumbers(block.text).some((n) => !n.junk);
        continue;
      }

      const tr = block.type === "table" ? block.element.closest("tr") : null;
      if (tr) {
        if (rowUnits.has(tr)) {
          const unit = rowUnits.get(tr);
          if (unit) unit.blockIndexes.push(block.index);
          continue;
        }
        const unit = rowUnit(tr, block, blockCells.get(tr) || new Set(), score, headerRows);
        rowUnits.set(tr, unit);
        if (unit) units.push(unit);
        continue;
      }

      if (!PROSE_TYPES.has(block.type) && block.type !== "table") continue;
      const bold = [...block.element.querySelectorAll("b, strong")]
        .map(cellText)
        .filter((t) => t.length >= 10);
      score.splitSentences(block.text).forEach((sentence, i) => {
        units.push({
          kind: "sentence",
          text: sentence.text,
          sentence: { start: sentence.start, end: sentence.end },
          blockText: block.text,
          element: block.element,
          highlight: block.element,
          group: block.index,
          table: null,
          order: block.index + i / 1000,
          blockIndexes: [block.index],
          context: {
            inTable: block.type === "table",
            bold: bold.some((b) => sentence.text.includes(b) || b.includes(sentence.text)),
            underNumberHeading: headingHasNumber,
          },
        });
      });
    }
    return units;
  }

  function rowUnit(tr, firstBlock, cellsWithBlocks, score, headerRows) {
    const table = tr.closest("table");
    if (!table) return null;
    // Per table, once: the header row and its column texts (colspans expanded).
    if (!headerRows.has(table)) {
      const row = headerRowOf(table, score);
      headerRows.set(table, { row, texts: row ? expandRow(row).map(cellText) : [] });
    }
    const header = headerRows.get(table);
    if (tr === header.row || tr.parentElement.tagName === "THEAD") return null;

    // The row's cells joined with " | " (which never joins two numbers into a range), run
    // through detection once; each number is mapped back to its cell by position. One call
    // per row instead of one per cell matters on big financial tables.
    const parts = [];
    const spans = []; // [start, end, cell]
    let offset = 0;
    for (const cell of tr.cells) {
      const text = cellText(cell);
      if (!text) continue;
      if (parts.length) offset += 3; // " | "
      spans.push([offset, offset + text.length, cell, text]);
      parts.push(text);
      offset += text.length;
    }
    const rowText = parts.join(" | ");
    const numbers = score.detectNumbers(rowText, { inTable: true });
    const figureCells = [];
    for (const n of numbers) {
      if (n.junk || NOT_FIGURES.has(n.type)) continue;
      const span = spans.find(([start, end]) => n.start >= start && n.start < end);
      if (span && !figureCells.includes(span[2])) figureCells.push(span[2]);
    }
    const target = figureCells.find((c) => cellsWithBlocks.has(c));
    if (!target) return null;

    const headers = [];
    if (header.texts.length) {
      expandRow(tr).forEach((cell, i) => {
        const text = header.texts[i];
        if (text && figureCells.includes(cell) && !headers.includes(text)) headers.push(text);
      });
    }
    return {
      kind: "row",
      text: rowText,
      cells: spans.map(([start, end, cell, text]) => ({ start, end, element: cell, text })),
      numbers,
      headers,
      element: target,
      highlight: tr,
      group: `row:${firstBlock.index}`,
      table,
      order: firstBlock.index,
      blockIndexes: [firstBlock.index],
      context: { inTable: true },
    };
  }

  // ---------------------------------------------------------------------------
  // Mapping cleaned text back to the page (step 9)
  // ---------------------------------------------------------------------------

  // A block's text is cleaned (whitespace collapsed, citation markers removed, read through
  // innerText), so its positions don't match the DOM. alignment() lines the cleaned text up
  // with the element's visible text nodes, character by character: whitespace runs match
  // whitespace runs (including &nbsp; and line breaks), letters compare case-insensitively
  // (innerText applies CSS text-transform), and citation markers like "[1]" that the cleaned
  // text dropped are skipped in the DOM. Each cleaned character maps to { node, offset } or
  // null. If the two texts stop agreeing, everything after that point stays null.
  // Built fresh on each call: highlighting splits text nodes, so a cached map would go stale.
  const MARKER_AT = new RegExp(MARKERS.source, "iy");

  function alignment(element, text) {
    const chars = [];
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const parent = node.parentElement;
      if (!parent || parent.closest("script, style, noscript, template")) continue;
      if (!parent.checkVisibility({ visibilityProperty: true })) continue;
      for (let k = 0; k < node.data.length; k++) chars.push({ node, offset: k });
    }
    const dom = chars.map((c) => c.node.data[c.offset]).join("");
    const isSpace = (ch) => /\s/.test(ch);
    const map = new Array(text.length).fill(null);
    let j = 0;
    outer: for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      if (isSpace(ch)) {
        // A space in the cleaned text matches a whitespace run in the DOM, if there is one
        // (innerText can add a space between elements that the DOM doesn't have).
        if (j < dom.length && isSpace(dom[j])) {
          map[i] = chars[j];
          while (j < dom.length && isSpace(dom[j])) j++;
        }
        continue;
      }
      while (j < dom.length && dom[j].toLowerCase() !== ch.toLowerCase()) {
        if (isSpace(dom[j])) {
          j++;
          continue;
        }
        MARKER_AT.lastIndex = j;
        const marker = MARKER_AT.exec(dom);
        if (marker) {
          j += marker[0].length;
          continue;
        }
        break outer; // the texts disagree: leave the rest unmapped
      }
      if (j >= dom.length) break;
      map[i] = chars[j];
      j++;
    }
    return map;
  }

  // DOM Ranges covering cleaned-text positions [start, end) of a block ({ element, text }):
  // one Range per text node the characters span ("<b>$12.4</b>B" gives two). Returns null if
  // any non-space character can't be mapped.
  function rangesFor(block, start, end) {
    const map = alignment(block.element, block.text);
    const pieces = [];
    let current = null;
    for (let i = start; i < end; i++) {
      const at = map[i];
      if (!at) {
        if (isSpaceChar(block.text[i])) {
          current = null;
          continue;
        }
        return null;
      }
      if (current && current.node === at.node && current.end === at.offset) current.end += 1;
      else {
        current = { node: at.node, start: at.offset, end: at.offset + 1 };
        pieces.push(current);
      }
    }
    return pieces
      .filter((p) => p.node.data.slice(p.start, p.end).trim())
      .map((p) => {
        const range = document.createRange();
        range.setStart(p.node, p.start);
        range.setEnd(p.node, p.end);
        return range;
      });
  }
  const isSpaceChar = (ch) => /\s/.test(ch || "");

  window.FrogbotExtract = { findMainContainer, getBlocks, buildUnits, rangesFor };
})();
